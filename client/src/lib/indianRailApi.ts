/**
 * Dynamically loads Google Maps JavaScript API script
 */
export function loadGoogleMapsScript(apiKey: string): Promise<boolean> {
  return new Promise((resolve) => {
    if (typeof window === "undefined") {
      resolve(false);
      return;
    }
    if ((window as any).google && (window as any).google.maps) {
      resolve(true);
      return;
    }
    const cleanKey = apiKey.trim();
    const existing = document.getElementById("google-maps-api-script") as HTMLScriptElement | null;
    if (existing) {
      if ((window as any).google && (window as any).google.maps) {
        resolve(true);
      } else {
        existing.addEventListener("load", () => resolve(true));
        existing.addEventListener("error", () => resolve(false));
      }
      return;
    }

    const script = document.createElement("script");
    script.id = "google-maps-api-script";
    script.src = `https://maps.googleapis.com/maps/api/js?key=${encodeURIComponent(
      cleanKey
    )}&libraries=places,geometry`;
    script.async = true;
    script.defer = true;
    script.onload = () => {
      resolve(true);
    };
    script.onerror = () => {
      resolve(false);
    };
    document.head.appendChild(script);
  });
}

/**
 * Fetches real station coordinates from IndianRailAPI
 * http://indianrailapi.com/api/v2/StationLocationOnMap/apikey/<apikey>/StationCode/<StationCode>
 */
export async function fetchStationLocationFromApi(
  stationCode: string,
  apiKey?: string
): Promise<{ lat: number; lng: number; raw?: any } | null> {
  const key = (apiKey || getStoredIndianRailApiKey()).trim();
  if (!key || key === "<apikey>") {
    return null;
  }

  const url = `http://indianrailapi.com/api/v2/StationLocationOnMap/apikey/${encodeURIComponent(
    key
  )}/StationCode/${encodeURIComponent(stationCode.toUpperCase())}`;

  try {
    const res = await fetch(url);
    if (!res.ok) return null;
    const data = await res.json();

    if (data && (data.Latitude || data.latitude || data.lat)) {
      const lat = parseFloat(data.Latitude || data.latitude || data.lat);
      const lng = parseFloat(data.Longitude || data.longitude || data.lng || data.long);
      if (!isNaN(lat) && !isNaN(lng)) {
        return { lat, lng, raw: data };
      }
    }
  } catch (err) {
    console.warn("IndianRailAPI fetch failed, falling back to local registry:", err);
  }

  return null;
}
