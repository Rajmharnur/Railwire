export interface GeoStation {
  name: string;
  code: string;
  lat: number;
  lng: number;
  km: number;
  division: string;
  zone: string;
  state: string;
  elevationM: number;
  platforms: number;
  interlockingType: string;
  kavachEnabled: boolean;
  corridorId: string;
  isJunction?: boolean;
  apiSynced?: boolean;
}

export interface GeoTrain {
  number: string;
  name: string;
  type:
    | "VANDE_BHARAT"
    | "RAJDHANI"
    | "SHATABDI_GATIMAAN"
    | "SUPERFAST"
    | "EXPRESS"
    | "FREIGHT_CONTAINER"
    | "MAINTENANCE_SPECIAL";
  lat: number;
  lng: number;
  speedKmh: number;
  headingDeg: number;
  origin: string;
  destination: string;
  nextStation: string;
  status: "ON_TIME" | "DELAYED" | "HELD_LOOP" | "WORK_ZONE";
  delayMins: number;
  signalAspect: "DOUBLE_GREEN" | "GREEN" | "YELLOW" | "RED";
  corridorId: string;
}

