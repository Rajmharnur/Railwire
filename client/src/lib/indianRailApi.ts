const LOCAL_STORAGE_API_KEY = "indian_rail_api_key";
const LOCAL_STORAGE_GOOGLE_MAPS_KEY = "google_maps_api_key";

export function getStoredIndianRailApiKey(): string {
  if (typeof window === "undefined") return "";
  return localStorage.getItem(LOCAL_STORAGE_API_KEY) || "";
}

export function setStoredIndianRailApiKey(key: string): void {
  if (typeof window === "undefined") return;
  localStorage.setItem(LOCAL_STORAGE_API_KEY, key.trim());
}

export function getStoredGoogleMapsApiKey(): string {
  if (typeof window === "undefined") return "";
  const key =
    localStorage.getItem(LOCAL_STORAGE_GOOGLE_MAPS_KEY) ||
    (import.meta as any).env?.VITE_GOOGLE_MAPS_API_KEY ||
    "";
  if (key.startsWith("AQ.Ab8")) return "";
  return key;
}

export function setStoredGoogleMapsApiKey(key: string): void {
  if (typeof window === "undefined") return;
  localStorage.setItem(LOCAL_STORAGE_GOOGLE_MAPS_KEY, key.trim());
}

